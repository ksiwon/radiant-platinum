// Pillow 11.3 `Image.fromarray(src, 'RGBA').resize((4, 3), Image.LANCZOS)`의 실측 바이트 (9×7 → 4×3, 시드 7의 난수 + 알파 0 · 128 · 255 · 77 줄).
// ⚠️ 알파가 섞인 칸이 있어야 한다 — 알파 255뿐이면 곱하고 나누는 쪽이 틀려도 안 걸린다
const SRC = [139, 74, 229, 0, 169, 65, 6, 0, 149, 106, 38, 0, 188, 205, 175, 229, 98, 249, 10, 148, 95, 86, 147, 198, 66, 39, 106, 213, 171, 45, 167, 57, 69, 81, 55, 14, 153, 178, 215, 128, 52, 39, 250, 128, 215, 50, 161, 128, 112, 172, 161, 233, 38, 17, 89, 1, 221, 6, 242, 127, 143, 6, 60, 210, 94, 25, 166, 33, 249, 189, 12, 204, 33, 57, 124, 255, 199, 149, 202, 255, 72, 220, 3, 255, 122, 136, 147, 255, 133, 82, 115, 255, 162, 230, 70, 255, 240, 62, 47, 255, 31, 34, 63, 255, 146, 197, 142, 255, 81, 133, 240, 77, 30, 247, 103, 77, 31, 19, 42, 77, 141, 136, 33, 77, 161, 0, 178, 77, 107, 35, 107, 77, 72, 27, 217, 77, 99, 13, 195, 77, 59, 228, 235, 77, 183, 47, 69, 179, 82, 35, 71, 159, 110, 121, 77, 87, 3, 126, 44, 253, 233, 225, 90, 119, 137, 120, 30, 55, 33, 165, 87, 216, 229, 167, 3, 41, 109, 203, 129, 219, 63, 101, 207, 156, 27, 220, 93, 29, 143, 200, 63, 11, 11, 180, 219, 113, 190, 87, 34, 9, 133, 29, 61, 36, 244, 192, 207, 131, 254, 67, 99, 248, 47, 71, 89, 119, 137, 85, 246, 206, 214, 129, 203, 234, 113, 121, 206, 210, 200, 248, 20, 161, 52, 114, 255, 112, 206, 54, 157, 131, 133, 69, 42, 68, 243, 24, 51, 127, 8, 205, 30, 97]
const WANT = [117, 114, 186, 111, 146, 179, 141, 162, 137, 78, 110, 182, 150, 84, 71, 136, 94, 111, 113, 151, 90, 132, 78, 146, 153, 105, 95, 133, 109, 126, 118, 159, 140, 92, 183, 140, 97, 172, 123, 105, 168, 114, 138, 85, 168, 110, 89, 139]

describe('알파를 곱해 줄이기 (`resizePremultiplied`)', () => {
  it('PIL의 RGBA `LANCZOS` 줄이기와 바이트가 같다', () => {
    const got = resizePremultiplied(Uint8Array.from(SRC), 9, 7, 4, 3)
    expect(Array.from(got)).toEqual(WANT)
  })
  it('같은 크기면 그대로 복사한다', () => {
    const got = resizePremultiplied(Uint8Array.from(SRC), 9, 7, 9, 7)
    expect(Array.from(got)).toEqual(SRC)
  })
})

describe('RGBA64 (형식 74)', () => {
  it('채널마다 위 8비트만 쓴다 (Pillow `RGBA;16L`)', () => {
    // 한 칸: R=0x1234 G=0x56AB B=0x9CDE A=0xFF01 — 리틀 엔디언이라 높은 바이트가 뒤다
    const raw = Uint8Array.from([0x34, 0x12, 0xAB, 0x56, 0xDE, 0x9C, 0x01, 0xFF])
    const tex = readTexture({ m_TextureFormat: 74, m_Width: 1, m_Height: 1, m_Name: 't', 'image data': raw }, {} as Bundle)
    expect(Array.from(tex.pixels)).toEqual([0x12, 0x56, 0x9C, 0xFF])
  })
})
