  0, 6, 12, 19, 25, 31, 37, 43, 49, 54, 60, 65, 71, 76, 81, 85, 90, 94, 98, 102, 106, 109, 112,
  115, 117, 120, 122, 123, 125, 126, 126, 127, 127,
