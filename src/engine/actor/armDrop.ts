// 몸마다 팔을 더 내리는 몫 (`Rig.armDropBias`)
//
// `gait`의 `armDrop`(1.25rad)은 주인공 여자 몸(`pc0002_00`)에서 잰 값이다 — 팔꿈치가 몸통 겉에서 팔 반지름의 1.16배 떨어진다.
// 바인드 팔은 번들 91벌이 다 수평이고 내린 뒤의 상완도 다 연직에서 19~20°라 **각은 같은데 몸통 폭이 다르다**. 그래서 몸통이
// 넓은 몸은 팔이 옆구리에서 떠 A자로 섰다 — 갤럭시단 조무래기(`tr1073_00`)가 2.28배였다(집회장의 서른여섯이 마네킹처럼 섰다).
//
// 값은 몸마다 **같은 자로 잰 것**이다(`armDrop.test.ts`가 다시 잰다): 바인드 스킨에서 몸통 · 팔 정점을 지배 본으로 가르고,
// 서 있는 자세에서 팔꿈치가 몸통 겉에서 팔 반지름의 몇 배인지를 본다. 정지가 1.4배를 넘는 몸만 0.01씩 더 내려 1.2배 안으로
// 들인다 — 걷기 0.7 · 달리기 0.6 밑으로 파고드는 몫까지는 안 내린다. 1보다 작은 몸은 손대지 않는다(치마 · 넓은 옷이 몸통으로
// 잡혀 값이 음수로도 나온다 — 그쪽은 잰 값이 몸이 아니다)
export const ARM_DROP_BIAS: Readonly<Record<string, number>> = {
  pc0001_00: 0.06,
  tr0031_00: 0.12, tr0042_00: 0.06, tr0053_00: 0.14, tr0062_00: 0.12,
  tr1012_00: 0.14, tr1019_00: 0.20, tr1024_00: 0.09, tr1052_00: 0.13, tr1065_00: 0.16,
  tr1067_00: 0.21, tr1068_00: 0.09, tr1073_00: 0.19, tr1077_00: 0.04, tr1079_00: 0.13,
  tr1087_00: 0.04, tr1088_00: 0.20, tr2009_00: 0.06, tr2011_00: 0.06,
}

/** 모델 이름이나 경로(`models/npc/tr1073_00.glb` · `tr1073_00-looker`)에서 그 몸의 보정 — 없으면 0 */
export function armDropBiasOf(model: string | undefined): number {
  const m = /(?:tr|pc)\d{4}_\d{2}/.exec(model ?? '')
  return m ? ARM_DROP_BIAS[m[0]] ?? 0 : 0
}
