// 운하시티 체육관 — 떠 있는 판 (`gym_features.c`의 `CanalaveGym_*`)
//
// 여섯째 뱃지의 방이다. 층이 넷이고 **바닥이 없다** — 떠 있는 판 스물넷 위에
// 올라서면 판이 통째로 움직이고, 그것이 층을 오르내리는 유일한 길이다.
//
// 판마다 자리가 둘(A·B)이고 밟을 때마다 그 사이를 오간다. 갈래는 셋이다:
//
//   y  위아래로 오르내린다. 층이 바뀐다 (0↔1층 여덟 · 1↔2층 둘)
//   x  동서로 간다. 같은 층 안에서만
//   z  남북으로 간다. 같은 층 안에서만
//
// ⚠️ **빨간 판 둘만 세 층을 한 번에 오간다** (0층 ↔ 3층). 관장에게 가는
// 길이 그 둘이다.
//
// ⚠️ **통행이 층마다 통째로 다른 표다.** 다른 체육관은 격자 위에 얹는 판정을
// 내는데 이 방만 `CheckCollision`이 **늘 참을 낸다** — 지금 높이로 층을
// 고르고 그 층의 32×32 표가 답이다. 격자는 아예 안 본다.
//
// ⚠️ **밟는 것으로 움직인다.** 단추도 좌표 트리거도 아니고, 한 걸음 옮길
// 때마다 「지금 선 칸에 판이 있는가」를 묻는다 (`Field_ProcessStep`의 첫 줄)

