/**
 * 딛는 높이(칸)가 몇 층인가
 * (`height / MAP_OBJECT_TILE_SIZE / CANALAVE_DIST_BETWEEN_FLOORS`)
 */
export function canalaveFloorAt(height: number): number {
  return Math.min(3, Math.max(0, Math.floor(height / CANALAVE_FLOOR_HEIGHT)))
}

/**
 * 그 칸이 막혔는가 (`CanalaveGym_DynamicMapFeaturesCheckCollision`).
 *
 * ⚠️ **여기만 「모른다」가 없다.** 원작이 늘 `TRUE`를 내서 격자를 아예 안
 * 본다 — 이 방은 바닥이 없고 층마다 표가 곧 지형이다
 */
export function canalaveBlocked(height: number, tileX: number, tileZ: number): boolean {
  if (tileX < 0 || tileX >= 32 || tileZ < 0 || tileZ >= 32) return true
  return CANALAVE_COLLISION[canalaveFloorAt(height)]![tileZ * 32 + tileX] === 1
}

/** 그 판이 지금 어느 자리에 있는가 */
export function canalavePlatformAt(
  platform: CanalavePlatform, inB: boolean,
): { pos: readonly [number, number, number]; floor: number } {
  return inB
    ? { pos: platform.b, floor: platform.floorB }
    : { pos: platform.a, floor: platform.floorA }
}

/** 처음 자리 표 (`startInPositionB`를 비트로 접은 것) */
export function canalaveInitialStates(): number {
  let bits = 0
  for (const [i, p] of CANALAVE_PLATFORMS.entries()) if (p.startB) bits |= 1 << i
  return bits
}

export function canalaveInB(states: number, index: number): boolean {
  return ((states >> index) & 1) !== 0
}

export function canalaveToggle(states: number, index: number): number {
  return states ^ (1 << index)
}

