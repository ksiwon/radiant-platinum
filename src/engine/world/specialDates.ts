// 특별한 날이 조우를 흔든다 (PARITY §6.12) — `src/overlay006/special_dates.c`.
//
// 마흔세 날이 걸음마다의 **평평한 관문**을 ±5·±10 움직인다. 출현률이 아니라
// 관문 쪽이라, 어느 맵에서든 똑같이 먹는다.
//
// ⚠️ **작은 값이 아니다.** 관문의 기본이 40이라 −10은 4분의 1을 깎는 것이고,
// 긴 풀 위(70)에서도 +10이면 80이다. 원작이 명절·기념일에 "오늘은 좀
// 다르네"를 심어 둔 자리다.
//
// 표는 눈으로 옮기지 않았다 — `sJanuaryDays` … `sDecemberDays` 열두 배열의
// `DateMod(날, 보정)`을 그대로 폈다.

/** `sEncounterRateModifiers` — 표가 가리키는 다섯 값 */
const MOD = [0, -5, +5, -10, +10] as const

/**
 * 달마다 `[날, 보정색인]`.
 *
 * ⚠️ **보정 0인 날이 넷 있다** (2월 14일 · 5월 1일 · 5월 4일 · 11월 23일).
 * 지우면 안 된다 — 원작 표에 그 날이 있고, 값이 0이라 아무 일도 안 일어날 뿐이다.
 * 지워 버리면 "왜 이 날만 표에 없지"를 나중에 다시 조사하게 된다
 */
const DAYS: readonly (readonly (readonly [number, number])[])[] = [
  [[1, 3], [11, 2], [12, 4], [29, 2]],
  [[3, 2], [11, 2], [14, 0], [27, 4]],
  [[3, 2], [18, 2], [21, 3]],
  [[1, 2], [25, 2], [26, 1], [29, 2]],
  [[1, 0], [3, 2], [4, 0], [5, 2]],
  [[21, 2]],
  [[7, 4], [18, 2], [24, 2]],
  [[13, 1], [14, 1], [15, 2], [16, 1]],
  [[7, 2], [12, 2], [15, 2], [20, 2], [23, 3], [28, 2]],
  [[5, 2], [15, 2], [30, 2]],
  [[3, 1], [12, 2], [21, 2], [23, 0]],
  [[14, 2], [23, 2], [31, 1]],
]

/** 표에 든 날의 수. 시험이 이걸로 표를 센다 */
export const SPECIAL_DATE_COUNT = DAYS.reduce((n, m) => n + m.length, 0)

/**
 * 오늘의 관문 보정 (`SpecialDates_ModifyEncounterRate`).
 *
 * ⚠️ **관문이 0이면 그대로 0이다.** 조우가 없는 곳을 특별한 날이 열지 않는다.
 *
 * ⚠️ **0 밑으로는 1이다.** 0이 아니다 — 원작이 `newModifier = 1`로 잡아 둔다.
 * 0으로 두면 그 날 하루 조우가 완전히 막힌다
 *
 * `penalty`는 시계를 최근에 돌렸을 때 원작이 세우는 표식이다. 서면 이 보정이
 * 통째로 쉰다 — 날짜를 앞뒤로 돌려 좋은 날만 골라 쓰는 것을 막는 자리다
 */
export function dateGate(gate: number, month: number, day: number, penalty = false): number {
  if (penalty) return gate
  if (gate === 0) return 0
  const found = DAYS[month - 1]?.find(([d]) => d === day)
  if (!found) return gate
  const next = gate + MOD[found[1]]!
  return next < 0 ? 1 : next
}
