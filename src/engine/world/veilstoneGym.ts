/** `MapObject_GetD{x,z}FromDir` — 북 0 · 남 1 · 서 2 · 동 3 */
export const VEILSTONE_STEP: readonly (readonly [number, number])[] = [
  [0, -1], [0, 1], [-1, 0], [1, 0],
]

/** `VEILSTONE_TILE_FLAG_*` */
export const VEILSTONE_FLAG = {
  cantMove: 1 << 0,
  tireStack: 1 << 1,
  pausePoint: 1 << 2,
} as const

export function veilstoneTileAt(x: number, z: number): number {
  if (x < 0 || x >= 32 || z < 0 || z >= 32) return 1
  return VEILSTONE_TILES[z * 32 + x]!
}

/** 자리 하나를 열쇠로. 타이어 표를 `Set`으로 들고 다닌다 */
export function veilstoneKey(x: number, z: number): string {
  return `${String(x)},${String(z)}`
}

/**
 * 그 칸에서 그 쪽으로 갈 때의 표시 (`VeilstoneGym_GetTileFlags`).
 *
 * ⚠️ **서 있는 칸과 갈 칸을 둘 다 본다.** 서 있는 칸의 값이 「그쪽으로는 못
 * 간다」를 말하고, 갈 칸의 값이 벽인지·타이어가 있는지를 말한다
 */
export function veilstoneFlags(
  x: number, z: number, dir: number, stacks: ReadonlySet<string>,
): number {
  let flags = 0
  const here = veilstoneTileAt(x, z)
  if (here === 4) flags |= VEILSTONE_FLAG.pausePoint
  else if (here === 2 && (dir === 0 || dir === 1)) flags |= VEILSTONE_FLAG.cantMove
  else if (here === 3 && (dir === 2 || dir === 3)) flags |= VEILSTONE_FLAG.cantMove
  else if (here === 5 && dir === 2) flags |= VEILSTONE_FLAG.cantMove

  const [dx, dz] = VEILSTONE_STEP[dir] ?? [0, 0]
  const nx = x + dx, nz = z + dz
  if (veilstoneTileAt(nx, nz) === 1) flags |= VEILSTONE_FLAG.cantMove
  if (stacks.has(veilstoneKey(nx, nz))) flags |= VEILSTONE_FLAG.tireStack
  return flags
}

/**
 * 찬 샌드백이 몇 칸을 가는가 (`VeilstoneGym_CalculateDistanceBagWillTravel`).
 *
 * ⚠️ **출발 칸의 「멈춤」은 안 센다.** 서 있는 자리가 멈춤 칸이어도 그 한 번은
 * 지나간다 — 안 그러면 멈춤 칸에 놓인 샌드백이 영영 안 움직인다
 */
export function veilstoneTravel(
  x: number, z: number, dir: number, stacks: ReadonlySet<string>,
): { distance: number; flags: number } {
  let flags = veilstoneFlags(x, z, dir, stacks)
  if (flags !== 0 && flags !== VEILSTONE_FLAG.pausePoint) return { distance: 0, flags }

  const [dx, dz] = VEILSTONE_STEP[dir] ?? [0, 0]
  let distance = 0
  let cx = x, cz = z
  do {
    cx += dx
    cz += dz
    distance++
    flags = veilstoneFlags(cx, cz, dir, stacks)
    // 원작에 없는 안전줄이다 — 표가 잘못돼 벽이 안 나오면 영영 돈다
    if (distance > 32) return { distance, flags: VEILSTONE_FLAG.cantMove }
  } while (flags === 0)
  return { distance, flags }
}

