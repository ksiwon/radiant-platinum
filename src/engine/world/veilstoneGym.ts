// 장막시티 체육관 — 샌드백과 타이어 (`gym_features.c`의 `VeilstoneGym_*`)
//
// 넷째 뱃지의 방이다. 샌드백 아홉을 **차서 미끄러뜨려** 타이어 더미 열하나를
// 무너뜨리면 길이 열린다. 그 둘이 길을 막고 있어서 없으면 관장에게 못 간다.
//
// ⚠️ **샌드백은 한 칸씩 밀리지 않는다.** 괴력 바위와 다르다 — 차면 **멈출
// 자리까지 통째로 미끄러진다**. 어디서 멈추는지는 이 방에만 있는 32×32 표가
// 정한다 (`sVeilstoneTileBehaviors`):
//
//   0  지나간다
//   1  벽. 여기로는 못 간다
//   3  동서로는 못 간다 (남북은 지나간다)
//   4  **여기서 멈춘다**
//   5  서쪽으로만 못 간다
//
// (2 = 「남북으로 못 간다」도 원작 주석에 있는데 표에 한 칸도 없다 — 실측)
//
// ⚠️ **타이어 더미 열하나 중 아홉은 벽 위에 서 있다.** 표만으로도 이미 막힌
// 자리인데 따로 세는 이유는 **무너뜨릴 것인지**를 가르기 위해서다 — 벽에
// 부딪히면 그냥 멈추고 타이어에 부딪히면 그것이 사라진다.
//
// ⚠️ **남은 둘(12,7 · 12,10)은 벽이 아니라 빈 칸에 서 있다.** 그 둘은 앞의
// 「멈춤」 칸으로 다가가야 걸리는 자리라, **타이어를 세는 판정이 없으면
// 샌드백이 그 위를 지나가 버린다** — 실측으로 확인했다
//
// ⚠️ **막는 것이 표가 아니라 객체다.** 원작의 `CheckCollision`이 그냥 거짓을
// 내고, 샌드백·타이어가 지도 객체라 그쪽 판정에 걸린다. 우리에게는 그 자리에
// 세울 객체가 없어서 장치 판정으로 대신 막는다 — 결과가 같다

