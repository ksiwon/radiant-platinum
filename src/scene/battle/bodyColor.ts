// 종족의 몸 색 (DATA.md §2.5의 +25 `color`).
//
// 모델이 있는 종은 그 모델이 서고(GLB 557개), **짝이 없는 폼만** 무대에 도형
// 으로 선다. 그 색을 **롬이 정한 몸 색으로 칠한다** — 아무 색이나 고르면
// 모부기가 파랗고 피카츄가 회색인, 화면을 볼 때마다 거슬리는 자리가 된다.
//
// 값은 4세대 도감의 색 분류 열 가지다. 대조: 모부기 3(초록) · 팽도리 1(파랑) ·
// 피카츄 2(노랑) · 팬텀 6(보라) · 잠만보 4(검정) · 찌르꼬 5(갈색).

/** 롬 색 번호 0~9. 508종 중 두 종만 10을 쓰는데 그건 빈 자리다 */
export const BODY_COLORS = [
  '#c0453c', // 0 빨강
  '#3f6fbf', // 1 파랑
  '#d9b23c', // 2 노랑
  '#4f9e52', // 3 초록
  '#3a3f4a', // 4 검정
  '#8a6440', // 5 갈색
  '#8358a8', // 6 보라
  '#8b9099', // 7 회색
  '#d8d5cc', // 8 하양
  '#d98fae', // 9 분홍
] as const

/** 색 번호가 표를 벗어나면 회색. 도형이 안 보이는 것보다 낫다 */
export function bodyColor(color: number): string {
  return BODY_COLORS[color] ?? BODY_COLORS[7]
}
