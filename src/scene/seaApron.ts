// 안 깔면 그 자리는 안개 바닥(`FogFloor`)의 안개 색 판만 남아 운하시티 서쪽 · 남서쪽 바다가 허옇게 비었다
// (화면 확인 2026-10-12: 떡잎마을 서쪽 숲 끝에서 남쪽으로 보면 숲 너머가 베이지색 한 판이다).
