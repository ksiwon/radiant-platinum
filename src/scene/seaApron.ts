// 어디가 바다인가 — 행렬 0의 청크 칸(30×30)에서 **바깥 둘레와 이어진, BDSP 지역이 칸의 40% 미만만 덮는 칸**이다. 비어 있는 칸(원작에
// 청크가 없다)과 청크는 있지만 BDSP 땅이 거의 없는 칸(운하시티 남서쪽 · 대륙 둘레)이다. 값은 BDSP 지역 glb 열세 벌의 삼각형을 타일에
// 비춰(칸마다 5점) 덮은 비율을 재고, 바깥에서 4방향으로 번지게 해서 뽑았다 (`.audit`에 도구를 두지 않았다 — 재려면 같은 일을 다시 해야 한다).
// 안쪽에 갇힌 빈 칸(산 · 호수 안쪽)은 바다가 아니라 안 깐다.
//
// 높이 — BDSP 바다 판의 y다(`area001`의 `SeaWater` 실측 0.98). 재질은 `WATER_LOOKS.M_C_001_SeaWater_01`의 빛깔이고 월드 자리로만
// 물결을 계산하므로(`waterMaterial`) 어느 자리에 깔아도 BDSP 바다와 이음매가 없다.
