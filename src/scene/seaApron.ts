/** 바다 판 직사각형들 (타일). 바깥 둘레는 `SEA_MARGIN` 칸만큼 밖으로 늘인다 */
export function seaRects(map: readonly string[] = SEA_MAP, margin = SEA_MARGIN): TileRect[] {
  const h = map.length, w = map[0]!.length
  const cells: [number, number][] = []
  for (let z = -margin; z < h + margin; z++) {
    for (let x = -margin; x < w + margin; x++) {
      const inside = x >= 0 && z >= 0 && x < w && z < h
      if (!inside || map[z]![x] === '~') cells.push([x, z])
    }
  }
  return [
    ...mergeTiles(cells).map((r) => ({ x: r.x * CHUNK, z: r.z * CHUNK, w: r.w * CHUNK, h: r.h * CHUNK })),
    ...SEA_PATCHES,
  ]
}
